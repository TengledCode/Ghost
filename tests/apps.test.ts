describe('finding the app Aaron means', () => {
  it('finds Store apps like Claude, and prefers the exact name', () => {
    expect(pick('Claude')).toBe('Claude');
    expect(pick('claude')).toBe('Claude');
    expect(pick('antigravity')).toBe('Antigravity'); // not its IDE
    expect(pick('paint')).toBe('Paint');
    expect(pick('paint 3d')).toBe('Paint 3D');
  });
  it('matches whole words, usual short names and part of a name', () => {
    expect(pick('chrome')).toBe('Google Chrome');
    expect(pick('code')).toBe('Visual Studio Code');
    expect(pick('vscode')).toBe('Visual Studio Code');
    expect(pick('powershell')).toBe('Windows PowerShell'); // the shortest of the two
    expect(pick('cmd')).toBe('Command Prompt');
    expect(pick('calc')).toBe('Calculator');
    expect(pick('notepad.exe')).toBe('Notepad');
    expect(pick('tele')).toBe('Telegram');
  });
  it('never picks an uninstaller, a reset tool or a web link', () => {
    expect(pick('uninstall')).toBeNull();
    expect(pick('uninstall telegram')).toBeNull();
    expect(pick('telegram')).toBe('Telegram');
    expect(pick('reset spyder settings')).toBeNull();
    expect(pick('steam support center')).toBeNull();
    expect(APPS.filter(a => !launchable(a)).map(a => a.name)).toEqual(['Steam Support Center', 'Uninstall Telegram', 'Uninstall', 'Reset Spyder Settings']);
  });
  it('finds nothing for a command that merely exists on the PC, and offers what is close', () => {
    for (const q of ['logoff', 'shutdown', 'npm', '', '   ']) expect(pick(q)).toBeNull();
    expect(findApp('telegrm', APPS)).toEqual({ app: null, near: [] });
    expect(findApp('steamy', APPS).near).toEqual(['Steam']);
    expect(findApp('antigravity', APPS).near).toEqual(['Antigravity IDE']);
  });
  it('reads what Get-StartApps prints', () => {
    expect(parseStartApps('[{"Name":"Claude","AppID":"Claude_pzs8sxrjxfjjc!Claude"},{"Name":"Notepad","AppID":"x!App"}]')).toHaveLength(2);
    expect(parseStartApps('{"Name":"Claude","AppID":"Claude_pzs8sxrjxfjjc!Claude"}')).toEqual([{ name: 'Claude', id: 'Claude_pzs8sxrjxfjjc!Claude' }]);
    expect(parseStartApps('Get-StartApps : not recognized')).toEqual([]);
  });
});

describe('open_app', () => {
  const tmp = (p: string) => mkdtempSync(join(tmpdir(), p));
  function setup(apps = APPS) {
    const started: string[] = [];
    const host = { openExternal: async () => {}, openPath: async () => '', trash: async () => {}, apps: { list: async () => apps, start: async (a: StartApp) => { started.push(a.id); return ''; } } };
    const exec = new ToolExecutor(host, new MemoryStore(join(tmp('ghost-m-'), 'm.json')), new ReminderScheduler(join(tmp('ghost-r-'), 'r.json'), () => {}));
    return { exec, started };
  }

  it('starts the app by the id Windows gave it', async () => {
    const { exec, started } = setup();
    expect(await exec.run('open_app', { name: 'Claude' })).toBe('Opened Claude.');
    expect(await exec.run('open_app', { name: 'chrome' })).toBe('Opened Google Chrome.');
    expect(started).toEqual(['Claude_pzs8sxrjxfjjc!Claude', 'Chrome']);
  });
  it('starts nothing for a name that is not an installed app, and says what is close', async () => {
    const { exec, started } = setup();
    expect(await exec.run('open_app', { name: 'logoff' })).toMatch(/no installed app called "logoff"/);
    expect(await exec.run('open_app', { name: 'steamy' })).toMatch(/closest are: Steam\./);
    expect(await exec.run('open_app', { name: '' })).toMatch(/Which app/);
    expect(started).toEqual([]);
    expect(await setup([]).exec.run('open_app', { name: 'claude' })).toMatch(/Couldn't read the list/);
  });
  it('shows a card for anything that is a path, a protocol or a program file', () => {
    for (const name of ['claude', 'logoff', 'Visual Studio Code', 'paint 3d']) expect(classify('open_app', { name }), name).toBe('safe');
    for (const name of ['C:\\Windows\\System32\\logoff.exe', 'logoff.exe', 'claude.ps1', 'ms-settings:', 'evil.vbs', 'x.msc', 'shell:AppsFolder\\x', 'setup.msi ']) expect(classify('open_app', { name }), name).toBe('confirm');
  });
});
